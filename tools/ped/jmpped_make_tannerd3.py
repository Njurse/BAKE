#!/usr/bin/env python3
"""jmpped_make_tannerd3.py - extract Tanner into a JMPPED character folder.

Tanner itself is drawn natively (MP ped id 0). This builds `tannerd3`, an
authoring base that puts Tanner's TORSO/HEAD/arms from HAVANA.LEV into the six
JERI_* slots of a Jericho clone (same bones, so the bind offsets match), keeps
the Tanner legs/hands the clone already carries, and writes a character folder
that `jmpped_player.py --characters` (and `jmpped_import.py`) bakes like any
other. Its materials stay in the source page sets (s2_*, s23_*, s25_*) and are
retargeted onto the character's own sets by `texture_page_map` at bake time.

    python jmpped_make_tannerd3.py --level .../HAVANA.LEV --out MODS/mp/peds
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import jmpped_core as jc
import jmpped_entries as je
import jmpped_models as jm

UPPER = {
    "JERI_TORSO": "TORSO",
    "JERI_HEAD": "HEAD",
    "JERI_U_ARM_LEFT": "U_ARM_LEFT",
    "JERI_L_ARM_LEFT": "L_ARM_LEFT",
    "JERI_U_ARM_RIGHT": "U_ARM_RIGHT",
    "JERI_L_ARM_RIGHT": "L_ARM_RIGHT",
}


def _combine(texts: list[str]) -> str:
    out = ["# JMPPED combined model (generated by jmpped_make_tannerd3.py)\n",
           "# Tanner upper body on the Jericho skeleton; bind pose, Blender space.\n"]
    vbase = tbase = 0
    for text in texts:
        nv = nt = 0
        for line in text.splitlines():
            p = line.split()
            if not p or p[0] in ("#", "mtllib"):
                continue
            if p[0] == "v":
                nv += 1
            elif p[0] == "vt":
                nt += 1
            elif p[0] == "f":
                corners = []
                for c in p[1:]:
                    bits = c.split("/")
                    bits[0] = str(int(bits[0]) + vbase)
                    if len(bits) > 1 and bits[1]:
                        bits[1] = str(int(bits[1]) + tbase)
                    corners.append("/".join(bits))
                line = "f " + " ".join(corners)
            out.append(line + "\n")
        vbase += nv
        tbase += nt
    return "".join(out)


def make(level: str, out_dir: str, name: str = "Tanner D3",
         slug: str = "tannerd3", work: str | None = None) -> str:
    import jmpped_extract
    import jmpped_add_character
    import jmpped_model

    own = work is None
    work = work or tempfile.mkdtemp(prefix="jmpped_tannerd3_")
    try:
        if jmpped_extract.extract(level, work, reset=True, level="havana"):
            raise jc.JMPPEDError("extract failed")
        if jmpped_add_character.add_character(work, name, "Jericho", slug):
            raise jc.JMPPEDError("add_character failed")
        manifest = je.load_manifest(work)
        c = je.character(manifest, name)
        src_rel = manifest["source"]["project"]
        tanner = jc.load_json(os.path.join(
            work, src_rel, "source_models", "tanner", "source.json"))
        tparts = {p["name"]: p for p in tanner["parts"]}
        skel = jmpped_model.skeleton_for(work, c, manifest)
        model_abs = jmpped_model.model_path(work, c)
        names = (set(jmpped_model.part_names(c))
                 | set(skel["bindings"].values()))
        groups = jm.read_combined_obj(model_abs, names, blender=True)
        char_dir = os.path.join(work, c["folder"])
        crop_dir = os.path.join(char_dir, "textures", "crops")

        for part in c["parts"]:
            tname = UPPER.get(part["part"])
            if tname is None:
                continue
            tp = tparts[tname]
            g = jm.read_combined_obj(os.path.join(work, tp["obj_raw"]),
                                     {tname}, blender=False)[tname]
            off = jmpped_model.bind_offset(skel["bones"], part["part"],
                                           skel["bone_by_model"])
            groups[part["part"]] = {
                "verts": [(x + off[0], y + off[1], z + off[2])
                          for x, y, z in g["verts"]],
                "faces": g["faces"],
            }
            for old in part.get("crops", []):
                p = os.path.join(work, old["rgb"])
                if os.path.isfile(p):
                    os.remove(p)
            tmap = {int(k): int(v) for k, v in
                    (c.get("texture_page_map") or {}).items()}
            crops = []
            for crop in tp.get("crops", []):
                crop = dict(crop)
                crop["page_set"] = tmap.get(int(crop["page_set"]),
                                            int(crop["page_set"]))
                dst = os.path.join(crop_dir, "%s_set%d_t%d.png" % (
                    part["part"], crop["page_set"], crop["texture"]))
                shutil.copy2(os.path.join(work, crop["rgb"]), dst)
                crop["rgb"] = os.path.relpath(dst, work).replace(os.sep, "/")
                crop["rgb_sha256"] = jc.sha256_file(dst)
                crops.append(crop)
            part["crops"] = crops
            part["materials"] = [dict(m, page_set=tmap.get(int(m["page_set"]),
                                                           int(m["page_set"])))
                                 for m in tp.get("materials", [])]
            part["texture_page_sets"] = [tmap.get(int(v), int(v)) for v in
                                         tp.get("texture_page_sets", [2])]
            part["source_model"] = "tanner"
            part["obj_edit_sha256"] = ""
            part["obj_raw_sha256"] = ""

        order = [p["part"] for p in c["parts"]]
        order += sorted(n for n in groups if n not in order)  # reference (HIPS)
        texts = [jmpped_model.part_obj_text(n, groups[n]["verts"],
                                            groups[n]["faces"], blender=True)
                 for n in order]
        with open(model_abs, "w", encoding="utf-8", newline="\n") as f:
            f.write(_combine(texts))
        c["note"] = ("Tanner (HAVANA.LEV) upper body in the JERI slots; "
                     "generated by jmpped_make_tannerd3.py")
        idx = next(i for i, x in enumerate(manifest["characters"])
                   if x["name"] == name)
        manifest["characters"][idx] = c
        jc.save_json(os.path.join(work, "project.json"), manifest)
        jc.save_json(os.path.join(char_dir, "character.json"), c)
        jmpped_model.split_character(work, c, force=True)

        dest = os.path.join(os.path.abspath(out_dir), slug)
        if os.path.exists(dest):
            shutil.rmtree(dest)
        shutil.copytree(char_dir, dest)
        print("wrote %s" % dest)
        return dest
    finally:
        if own:
            shutil.rmtree(work, ignore_errors=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--level", required=True, help="HAVANA.LEV")
    ap.add_argument("--out", required=True, help="parent folder (e.g. MODS/mp/peds)")
    ap.add_argument("--name", default="Tanner D3")
    ap.add_argument("--slug", default="tannerd3")
    args = ap.parse_args(argv)
    try:
        make(args.level, args.out, args.name, args.slug)
    except jc.JMPPEDError as e:
        print("jmpped tannerd3: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
